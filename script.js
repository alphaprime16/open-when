const letterModal = document.getElementById("letterModal");
const poemModal = document.getElementById("poemModal");
const title = document.getElementById("letterTitle");
const body = document.getElementById("letterBody");
const poemButtonWrap = document.getElementById("poemButtonWrap");

document.querySelectorAll(".envelope").forEach(button => {
  button.addEventListener("click", () => {
    const key = button.dataset.letter;
    const letter = letters[key];
    title.textContent = letter.title;
    body.innerHTML = letter.body;
    poemButtonWrap.innerHTML = letter.poem
      ? '<button class="poem-button" id="openPoem">♡ There\'s a little poem attached to this one ♡</button>'
      : "";
    letterModal.classList.add("open");
    letterModal.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";

    const openPoem = document.getElementById("openPoem");
    if (openPoem) {
      openPoem.addEventListener("click", () => {
        poemModal.classList.add("open");
        poemModal.setAttribute("aria-hidden", "false");
      });
    }
  });
});

function closeModal(modal) {
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  if (!letterModal.classList.contains("open") && !poemModal.classList.contains("open")) {
    document.body.style.overflow = "";
  }
}

document.querySelectorAll(".close").forEach(button => {
  button.addEventListener("click", () => {
    closeModal(button.closest(".modal"));
  });
});

document.querySelectorAll(".modal-backdrop").forEach(backdrop => {
  backdrop.addEventListener("click", () => closeModal(backdrop.closest(".modal")));
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeModal(poemModal);
    closeModal(letterModal);
  }
});

// Soft floating hearts
const heartContainer = document.querySelector(".hearts");
function createHeart() {
  const heart = document.createElement("span");
  heart.className = "float-heart";
  heart.textContent = Math.random() > .45 ? "♡" : "✦";
  heart.style.left = `${Math.random() * 100}%`;
  heart.style.fontSize = `${10 + Math.random() * 15}px`;
  heart.style.animationDuration = `${8 + Math.random() * 8}s`;
  heartContainer.appendChild(heart);
  setTimeout(() => heart.remove(), 17000);
}
setInterval(createHeart, 1300);
